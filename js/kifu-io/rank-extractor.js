/**
 * KIFヘッダーの対局者名文字列（例:「斎藤明日斗 六段」「藤井聡太 名人」）から、
 * 名前本体と段級位/タイトルを分離する。
 *
 * 【背景】
 * KIFの対局者名は「先手：」「後手：」の1行に、名前と段級位が
 * 半角/全角スペース区切り、あるいは区切り無しで混在して書かれることがある
 * （専用の「先手段級：」フィールドとは別の書き方）。
 * このモジュールは、名前文字列の**末尾**が既知の段級位/タイトルパターンに
 * 一致するかどうかだけを見て分離する。一致しなければ何もせず、
 * 文字列全体をそのまま名前として扱う（安全側のフォールバック）。
 *
 * 【方針】
 * - 正規表現は「拾いすぎない」ことを最優先する。
 *   例：「加藤一二三」のように名前の一部が段位の漢数字と紛らわしいケースを
 *   誤って段級位と誤認識しないよう、パターンは検証済みの語彙リストに
 *   限定する（任意の位置ではなく、文字列の末尾に完全一致する場合のみ抽出）。
 * - 対応スコープ：
 *   - 段：初段、一段〜十段（漢数字）、1段〜10段（算用数字）
 *   - 級：1級〜30級（算用数字のみ。級は算用数字表記が一般的なため）
 *   - 八大タイトル：竜王・名人・王位・叡王・王座・棋王・王将・棋聖
 *   - 女流タイトル：白玲・清麗・女王・女流王座・女流名人・女流王位・
 *     女流王将・倉敷藤花
 *   - 永世称号：永世+タイトル名、〇世+タイトル名（一〜三十世）
 *   - 冠数表記：二冠〜八冠、女流二冠〜女流八冠
 *   - 竜王名人特殊表記：竜王名人、竜王・名人
 *   - アマチュア：アマ+段級位（例：アマ六段、アマ10級）
 *   - 奨励会：奨励会+段級位（例：奨励会三段）
 * - スコープ外（意図的に対象としない）：
 *   - 「（初代）」等の代数を示す敬称（段級位ではないため無関係。
 *     名前欄側の表示問題として別途対応済み）
 *   - 専用フィールド「先手段級：」「後手段級：」がある場合はそちらを
 *     優先し、本モジュールは呼び出されない（kif-parser.js側の制御）。
 */

// 段（初段、一段〜十段、1段〜10段）
const DAN_KANJI = '初|一|二|三|四|五|六|七八|七|八|九|十';
// 上記|区切りだと「七八」のような誤結合を招くため、実際は配列から individually 生成する
const DAN_KANJI_LIST = ['初', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十'];

// タイトル（8冠）
const TITLES = ['竜王', '名人', '王位', '叡王', '王座', '棋王', '王将', '棋聖'];

// 女流タイトル
const JORYU_TITLES = ['白玲', '清麗', '女王', '女流王座', '女流名人', '女流王位', '女流王将', '倉敷藤花'];

// 永世称号の代数（一世〜三十世）。長い表記から先にマッチさせるため降順の長さでソートする。
const SEI_NUM = [
  '三十', '二十九', '二十八', '二十七', '二十六', '二十五', '二十四', '二十三', '二十二', '二十一',
  '二十', '十九', '十八', '十七', '十六', '十五', '十四', '十三', '十二', '十一',
  '十', '九', '八', '七', '六', '五', '四', '三', '二', '一'
];

// 冠数表記（二冠〜八冠）
const KANSUU_NUM = ['二', '三', '四', '五', '六', '七', '八'];

/**
 * 文字列配列から「いずれかに完全一致」する正規表現の選択肢（OR）文字列を作る。
 * 長い候補から先に試すことで、短い候補による部分マッチの誤爆を防ぐ
 * （例：「女流王座」より先に「女王」が候補に入っていると誤ってそちらに
 * マッチしてしまう可能性があるため）。
 *
 * 【重要】この関数が返す文字列は "(?:...)" で囲んで使うことを前提とする。
 * 呼び出し側で `` `${alt}段` `` のように末尾へ接尾語を追記すると、
 * `|` の優先順位（一番右の候補だけに接尾語が掛かる）により
 * 「六|七|八段」のような意図しない結合になるので、
 * **接尾語を付けたい場合は必ず suffix 引数を使うこと**（呼び出し側で
 * 文字列補間しない）。
 * @param {string[]} list
 * @param {string} [suffix] - 各候補の末尾に付ける固定文字列（例:'段'）
 * @returns {string}
 */
function toAlternation(list, suffix = '') {
  return [...list]
    .sort((a, b) => b.length - a.length)
    .map((s) => `${s}${suffix}`)
    .join('|');
}

const TITLE_ALT = toAlternation(TITLES);
const JORYU_ALT = toAlternation(JORYU_TITLES);
// 冠数表記（二冠〜八冠）※タイトル全体の冠数
const KANSUU_ALT = toAlternation(KANSUU_NUM, '冠');
// 女流冠数表記（女流二冠〜女流八冠）※女流タイトルの冠数
// 【不具合修正】「里見香奈 女流四冠」のような表記が拾えていなかった。
// 通常の冠数表記（二冠〜八冠）とは別に、「女流」を伴う表記を専用に用意する。
const JORYU_KANSUU_ALT = toAlternation(KANSUU_NUM.map((n) => `女流${n}冠`));
// 〇世＋タイトルの全組み合わせを候補として生成し、長い順に並べる
// （SEI_NUM_ALT + '世' + TITLE_ALT という文字列結合方式は上記と同じ理由で
// 使わず、代数×タイトルの直積を個別候補として展開する）。
const SEI_TITLE_ALT = toAlternation(
  SEI_NUM.flatMap((n) => TITLES.map((t) => `${n}世${t}`))
);
// 段（初段、一段〜十段）。算用数字1〜10段は別途リテラルで扱う。
const DAN_KANJI_ALT = toAlternation(DAN_KANJI_LIST, '段');
// アマ＋段（アマ初段〜アマ十段）
const AMA_DAN_ALT = toAlternation(DAN_KANJI_LIST, '段').split('|').map((s) => `アマ${s}`).join('|');
// 奨励会＋段（奨励会初段〜奨励会十段）
const SHOUREIKAI_DAN_ALT = toAlternation(DAN_KANJI_LIST, '段').split('|').map((s) => `奨励会${s}`).join('|');
// 永世＋タイトル
const EISEI_TITLE_ALT = toAlternation(TITLES.map((t) => `永世${t}`));

/**
 * 末尾マッチ用パターンを優先度順（長い/具体的なものを先）に並べたリスト。
 * 各パターンは "(段級位部分)$" の形で使う（末尾固定）。
 * 注意：全パターンとも文字列の**末尾**に一致することを要求する（$固定）ため、
 * 「加藤一二三」のように末尾が段級位パターンそのもの（「段」「級」等の
 * 接尾語を伴わない裸の漢数字）では一致しない。
 */
const RANK_PATTERNS = [
  // 奨励会＋段級位（例: 奨励会三段, 奨励会1級）※固有名詞なので最優先
  new RegExp(`(${SHOUREIKAI_DAN_ALT}|奨励会[1-9][0-9]?級)$`),
  // アマ＋段級位（例: アマ六段, アマ10級, アマ十段）
  new RegExp(`(${AMA_DAN_ALT}|アマ[1-9][0-9]?級)$`),
  // 竜王・名人（特殊、中黒あり）
  /(竜王・名人)$/,
  // 竜王名人（特殊、中黒なし）
  /(竜王名人)$/,
  // 〇世＋タイトル（永世称号、代数表記）
  new RegExp(`(${SEI_TITLE_ALT})$`),
  // 永世＋タイトル
  new RegExp(`(${EISEI_TITLE_ALT})$`),
  // 女流冠数表記（女流二冠〜女流八冠）。通常の冠数表記（二冠〜八冠）より
  // 先に試す必要がある。逆順だと「女流四冠」の末尾「四冠」だけが
  // 通常冠数パターンにマッチしてしまい、「女流」が名前側に残って
  // 「里見香奈 女流」＋「四冠」に誤分割される（実際に発生したバグ）。
  new RegExp(`(${JORYU_KANSUU_ALT})$`),
  // 冠数表記（二冠〜八冠）
  new RegExp(`(${KANSUU_ALT})$`),
  // 女流タイトル
  new RegExp(`(${JORYU_ALT})$`),
  // 八大タイトル
  new RegExp(`(${TITLE_ALT})$`),
  // 段（初段、一段〜十段、算用数字1〜10段）
  new RegExp(`(${DAN_KANJI_ALT}|10段|[1-9]段)$`),
  // 級（1級〜30級。算用数字のみ）
  /([1-9][0-9]?級)$/
];

/**
 * KIFヘッダーの対局者名文字列から、名前本体と段級位/タイトルを分離する。
 * @param {string} rawName - 例:「斎藤明日斗 六段」「藤井聡太名人」「大橋宗桂（初代）」
 * @returns {{ name: string, rank: string|null }}
 *   一致しなかった場合は rank: null、name には rawName をそのまま返す
 *   （末尾の空白等のトリムのみ行う）。
 */
export function extractRank(rawName) {
  if (!rawName || typeof rawName !== 'string') {
    return { name: rawName || '', rank: null };
  }

  for (const pattern of RANK_PATTERNS) {
    const m = rawName.match(pattern);
    if (!m) continue;

    const rankPart = m[1];
    // 段級位部分より前を名前とする。名前と段級位の間の区切り文字
    // （半角/全角スペース）は、名前側の末尾から取り除く。
    // 区切りが無い場合（例:「藤井聡太名人」）はそのまま前方部分を名前とする。
    let namePart = rawName.slice(0, rawName.length - rankPart.length);
    namePart = namePart.replace(/[\s\u3000]+$/, '');

    // 名前部分が空になってしまう場合（＝文字列全体が段級位パターンそのもの）は、
    // 抽出結果を採用しない。対局者名が丸ごと消えるのは避ける安全側の判断。
    if (namePart.length === 0) continue;

    return { name: namePart, rank: rankPart };
  }

  return { name: rawName, rank: null };
}
